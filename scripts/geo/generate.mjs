// Generates the map's shapes as committed TypeScript modules (docs/adr/0006):
//
//   web/src/lib/geo/states.ts            the 50 states and DC, for the map
//   web/src/lib/geo/districts/<ST>.ts    one state's congressional districts
//   web/src/lib/geo/manifest.json        which shapes exist, for the tests
//
// Inputs, both pinned (the header of every output names them):
//   us-atlas's states-albers-10m.json: Census state boundaries, already
//     projected with d3.geoAlbersUsa into a 975 × 610 frame;
//   the Census Bureau's cb_2024_us_cd119_500k shapefile: the districts of
//     the 119th Congress, downloaded and checked by `make geo`.
//
// Each state's districts get their own equal-area projection fitted to a
// frame 600 units wide, so a small state keeps its detail. They are made a
// topology before simplifying, so neighbouring districts keep one shared
// border and no slivers open between them.
//
// Usage (in Node 22): node generate.mjs <input dir> <output dir>

import { createHash } from 'node:crypto';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { geoCentroid, geoConicEqualArea, geoPath } from 'd3-geo';
import * as shapefile from 'shapefile';
import { feature } from 'topojson-client';
import { topology } from 'topojson-server';
import { presimplify, simplify } from 'topojson-simplify';

const [inputDir = 'input', outDir = 'out'] = process.argv.slice(2);
const ATLAS = 'node_modules/us-atlas/states-albers-10m.json';
const ATLAS_VERSION = JSON.parse(await readFile('node_modules/us-atlas/package.json', 'utf8')).version;
const CD = path.join(inputDir, 'cb_2024_us_cd119_500k');
const CD_ZIP = `${CD}.zip`;

// A district map's frame, and how much detail survives simplification:
// a point whose triangle is smaller than MIN_AREA (in frame units squared)
// is dropped. One unit is 1/600 of the state's width.
const WIDTH = 600;
const MIN_AREA = 0.6;

// State and territory FIPS codes to postal codes.
const POSTAL = {
  '01': 'AL', '02': 'AK', '04': 'AZ', '05': 'AR', '06': 'CA', '08': 'CO', '09': 'CT', '10': 'DE', '11': 'DC',
  '12': 'FL', '13': 'GA', '15': 'HI', '16': 'ID', '17': 'IL', '18': 'IN', '19': 'IA', '20': 'KS', '21': 'KY',
  '22': 'LA', '23': 'ME', '24': 'MD', '25': 'MA', '26': 'MI', '27': 'MN', '28': 'MS', '29': 'MO', '30': 'MT',
  '31': 'NE', '32': 'NV', '33': 'NH', '34': 'NJ', '35': 'NM', '36': 'NY', '37': 'NC', '38': 'ND', '39': 'OH',
  '40': 'OK', '41': 'OR', '42': 'PA', '44': 'RI', '45': 'SC', '46': 'SD', '47': 'TN', '48': 'TX', '49': 'UT',
  '50': 'VT', '51': 'VA', '53': 'WA', '54': 'WV', '55': 'WI', '56': 'WY',
  '60': 'AS', '66': 'GU', '69': 'MP', '72': 'PR', '78': 'VI',
};

const sha256 = async (file) => createHash('sha256').update(await readFile(file)).digest('hex');
const round = (n) => Math.round(n * 10) / 10;

const header = (what, inputs) =>
  `// ${what}\n// Generated by scripts/geo/generate.mjs (make geo) from:\n` +
  inputs.map((i) => `//   ${i}\n`).join('') +
  '// Do not edit by hand: change the script and regenerate.\n';

const atlasLine = `us-atlas ${ATLAS_VERSION}, states-albers-10m.json (sha256 ${await sha256(ATLAS)}), from Census Bureau boundaries`;
const cdLine = `Census Bureau, cb_2024_us_cd119_500k.zip (sha256 ${await sha256(CD_ZIP)}): districts of the 119th Congress`;

// --- States -----------------------------------------------------------------
const atlas = JSON.parse(await readFile(ATLAS, 'utf8'));
const flat = geoPath().digits(1); // the atlas is already projected
const states = feature(atlas, atlas.objects.states)
  .features.map((f) => {
    const code = POSTAL[f.id];
    if (!code) throw new Error(`us-atlas state ${f.id} (${f.properties.name}) has no postal code`);
    const [x, y] = flat.centroid(f);
    return { code, name: f.properties.name, d: flat(f), label: [round(x), round(y)] };
  })
  .sort((a, b) => a.code.localeCompare(b.code));

// outDir holds only generated files (it may be a mount point, so it is
// emptied, not removed).
await rm(path.join(outDir, 'districts'), { recursive: true, force: true });
await mkdir(path.join(outDir, 'districts'), { recursive: true });
await writeFile(
  path.join(outDir, 'states.ts'),
  header('The map: the 50 states and DC, projected with d3.geoAlbersUsa into 975 × 610.', [atlasLine]) +
    "import type { StateShape } from '../geo-types';\n\n" +
    "export const viewBox = '0 0 975 610';\n\n" +
    `export const states: StateShape[] = ${JSON.stringify(states, null, 1)};\n`,
);

// --- Districts --------------------------------------------------------------
const source = await shapefile.read(`${CD}.shp`, `${CD}.dbf`);
const byState = new Map();
for (const f of source.features) {
  const code = POSTAL[f.properties.STATEFP];
  const fp = f.properties.CD119FP;
  if (!code) throw new Error(`district ${f.properties.GEOID} has an unknown state ${f.properties.STATEFP}`);
  if (fp === '98') continue; // DC and the territories: a delegate, no district map
  if (fp === 'ZZ') continue; // water not in any district
  const n = fp === '00' ? 0 : Number(fp);
  if (!Number.isInteger(n)) throw new Error(`district ${f.properties.GEOID} has a code ${fp}`);
  if (!byState.has(code)) byState.set(code, []);
  byState.get(code).push({ ...f, properties: { n } });
}

// mapCoords applies fn to every position of a geometry.
const mapCoords = (geom, fn) => {
  const walk = (c) => (typeof c[0] === 'number' ? fn(c) : c.map(walk));
  return { ...geom, coordinates: walk(geom.coordinates) };
};

const manifest = { congress: 119, states: states.map((s) => s.code), districts: {} };
for (const code of [...byState.keys()].sort()) {
  const fc = { type: 'FeatureCollection', features: byState.get(code).sort((a, b) => a.properties.n - b.properties.n) };
  const [lon] = geoCentroid(fc);
  // Rotating to the state's own longitude keeps the antimeridian far away,
  // so Alaska's Aleutians stay in one piece.
  const projection = geoConicEqualArea().rotate([-lon, 0]).parallels([29.5, 45.5]).fitWidth(WIDTH, fc);
  const planar = {
    type: 'FeatureCollection',
    features: fc.features.map((f) => ({ ...f, geometry: mapCoords(f.geometry, (p) => projection(p)) })),
  };
  const topo = presimplify(topology({ districts: planar }));
  const simple = simplify(topo, MIN_AREA);
  const shapes = feature(simple, simple.objects.districts).features;
  const [[, y0], [, y1]] = flat.bounds({ type: 'FeatureCollection', features: shapes });
  const height = Math.ceil(y1 - Math.min(0, y0));
  const districts = shapes.map((f) => {
    const [x, y] = flat.centroid(f);
    return { n: f.properties.n, d: flat(f), label: [round(x), round(y)] };
  });
  manifest.districts[code] = districts.map((d) => d.n);
  await writeFile(
    path.join(outDir, 'districts', `${code}.ts`),
    header(`${code}'s congressional districts of the 119th Congress, ${WIDTH} units wide.`, [cdLine]) +
      "import type { DistrictMap } from '../../geo-types';\n\n" +
      `const map: DistrictMap = ${JSON.stringify({ state: code, congress: 119, viewBox: `0 0 ${WIDTH} ${height}`, districts }, null, 1)};\n\n` +
      'export default map;\n',
  );
}

await writeFile(path.join(outDir, 'manifest.json'), `${JSON.stringify(manifest, null, 1)}\n`);
console.log(`wrote ${states.length} states and ${byState.size} district maps to ${outDir}`);
